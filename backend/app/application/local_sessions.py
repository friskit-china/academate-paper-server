from __future__ import annotations

import uuid
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Protocol

from app.domain.local_sessions import (
    IssuedLocalLaunchToken,
    IssuedLocalSessionToken,
    LocalSessionTokenCodec,
)


class LocalLaunchTokenInvalidError(PermissionError):
    pass


class LocalLaunchTokenExpiredError(PermissionError):
    pass


class LocalLaunchTokenReplayError(PermissionError):
    pass


class LocalSessionInvalidError(PermissionError):
    pass


class LocalSessionStateError(RuntimeError):
    """The installation cannot safely issue or exchange Local browser credentials."""


class LocalLaunchTokenRegistry(Protocol):
    def register_launch(self, issued: IssuedLocalLaunchToken, *, now: datetime) -> None: ...


class LocalSessionRepository(LocalLaunchTokenRegistry, Protocol):
    def exchange_launch(
        self,
        *,
        launch_digest: str,
        session_id: str,
        session_token: IssuedLocalSessionToken,
        now: datetime,
    ) -> None: ...

    def resolve_active_session(
        self,
        *,
        session_digest: str,
        now: datetime,
    ) -> str | None: ...

    def revoke_session(self, *, session_id: str, now: datetime) -> bool: ...


class IdentifierFactory(Protocol):
    def __call__(self) -> str: ...


def _new_identifier() -> str:
    return str(uuid.uuid4())


def _aware_time(value: datetime | None) -> datetime:
    resolved = value or datetime.now(UTC)
    if resolved.tzinfo is None:
        raise ValueError("Local session lifecycle timestamps must be timezone-aware.")
    return resolved


def _valid_raw_token(raw_token: str) -> bool:
    # Tokens generated by this runtime are currently 43 URL-safe characters.  A broad bound keeps
    # codec/version evolution possible while preventing attacker-controlled hashing of huge input.
    return 32 <= len(raw_token) <= 512 and raw_token.isascii()


@dataclass(frozen=True, slots=True)
class TrustedLocalLaunchTokenService:
    """Trusted launcher entrypoint; this service is never exposed as a browser API."""

    codec: LocalSessionTokenCodec
    registry: LocalLaunchTokenRegistry

    def issue(self, *, now: datetime | None = None) -> IssuedLocalLaunchToken:
        issued_at = _aware_time(now)
        issued = self.codec.issue_launch(now=issued_at)
        self.registry.register_launch(issued, now=issued_at)
        return issued


@dataclass(frozen=True, slots=True)
class LocalSessionExchangeResult:
    raw_session_token: str
    expires_at: datetime

    def __repr__(self) -> str:
        return (
            "LocalSessionExchangeResult(raw_session_token='**********', "
            f"expires_at={self.expires_at!r})"
        )


@dataclass(frozen=True, slots=True)
class LocalSessionExchangeService:
    codec: LocalSessionTokenCodec
    repository: LocalSessionRepository
    identifier_factory: IdentifierFactory = _new_identifier

    def exchange(
        self,
        raw_launch_token: str,
        *,
        now: datetime | None = None,
    ) -> LocalSessionExchangeResult:
        exchanged_at = _aware_time(now)
        if not _valid_raw_token(raw_launch_token):
            raise LocalLaunchTokenInvalidError("The browser launch proof is invalid.")
        session_token = self.codec.issue_session(now=exchanged_at)
        self.repository.exchange_launch(
            launch_digest=self.codec.launch_digest(raw_launch_token),
            session_id=self.identifier_factory(),
            session_token=session_token,
            now=exchanged_at,
        )
        return LocalSessionExchangeResult(
            raw_session_token=session_token.raw_token,
            expires_at=session_token.expires_at,
        )


@dataclass(frozen=True, slots=True)
class LocalSessionVerifier:
    codec: LocalSessionTokenCodec
    repository: LocalSessionRepository

    def verify(self, raw_session_token: str, *, now: datetime | None = None) -> str:
        verified_at = _aware_time(now)
        if not _valid_raw_token(raw_session_token):
            raise LocalSessionInvalidError("The Local browser session is invalid.")
        session_id = self.repository.resolve_active_session(
            session_digest=self.codec.session_digest(raw_session_token),
            now=verified_at,
        )
        if session_id is None:
            raise LocalSessionInvalidError("The Local browser session is invalid.")
        return session_id
